/**
 * Check if string is a valid 3-char or 6-char hex code
 */
export const isValidHex = (hex) =>
  typeof hex === "string" && /^#([A-Fa-f0-9]{3}|[A-Fa-f0-9]{6})$/.test(hex.trim());

/**
 * Resolve any valid CSS standard color name to a normalized 6-char hex code
 * Works dynamically in any browser environment via canvas 2D context.
 */
export const cssNameToHex = (colorName) => {
  if (typeof window === "undefined" || !colorName || typeof colorName !== "string") return "";
  const cleaned = colorName.trim().toLowerCase();
  if (!cleaned || cleaned.includes("<") || cleaned.includes(">")) return "";

  try {
    const canvas = document.createElement("canvas");
    canvas.width = 1;
    canvas.height = 1;
    const ctx = canvas.getContext("2d", { willReadFrequently: true });
    if (!ctx) return "";

    ctx.fillStyle = "#010203"; // Arbitrary sentinel color
    ctx.fillStyle = cleaned;
    const computed = ctx.fillStyle;

    if (computed === "#010203" && cleaned !== "#010203") {
      // Failed to parse color
      return "";
    }

    if (computed.startsWith("#")) {
      return normalizeHex(computed);
    }

    const rgbMatch = computed.match(/^rgba?\((\d+),\s*(\d+),\s*(\d+)/i);
    if (rgbMatch) {
      const r = parseInt(rgbMatch[1], 10).toString(16).padStart(2, "0");
      const g = parseInt(rgbMatch[2], 10).toString(16).padStart(2, "0");
      const b = parseInt(rgbMatch[3], 10).toString(16).padStart(2, "0");
      return `#${r}${g}${b}`.toUpperCase();
    }
  } catch (err) {
    // Graceful fallback
  }

  return "";
};

/**
 * Convert hex string (#ffffff or #fff) to RGB object { r, g, b }
 */
export const hexToRgb = (hex) => {
  if (!hex || typeof hex !== "string") return null;
  let clean = hex.replace("#", "").trim();
  if (clean.length === 3) {
    clean = clean
      .split("")
      .map((c) => c + c)
      .join("");
  }
  if (clean.length !== 6) return null;
  const num = parseInt(clean, 16);
  if (isNaN(num)) return null;
  return {
    r: (num >> 16) & 255,
    g: (num >> 8) & 255,
    b: num & 255,
  };
};

/**
 * Normalize hex string to standard 6-char uppercase (#RRGGBB)
 */
export const normalizeHex = (hex) => {
  if (!hex || typeof hex !== "string") return "";
  let clean = hex.replace(/[^0-9A-Fa-f]/g, "");
  if (clean.length === 3) {
    clean = clean
      .split("")
      .map((c) => c + c)
      .join("");
  }
  if (clean.length >= 6) {
    return `#${clean.substring(0, 6).toUpperCase()}`;
  }
  return hex.startsWith("#") ? hex : `#${hex}`;
};

/**
 * Find the closest named fabric color for any arbitrary hex code
 */
export const findClosestFabricColor = (hex) => {
  const targetRgb = hexToRgb(hex);
  if (!targetRgb) return null;

  let closest = null;
  let minDistance = Infinity;

  FABRIC_COLORS.forEach((color) => {
    const rgb = hexToRgb(color.hex);
    if (!rgb) return;
    const distance = Math.sqrt(
      Math.pow(targetRgb.r - rgb.r, 2) +
      Math.pow(targetRgb.g - rgb.g, 2) +
      Math.pow(targetRgb.b - rgb.b, 2)
    );
    if (distance < minDistance) {
      minDistance = distance;
      closest = color;
    }
  });

  return closest;
};

/**
 * Generate a consistent, pleasant vibrant or pastel hex color from any arbitrary string
 * Used as an intelligent fallback preview for unique custom fabric names.
 */
export const getDeterministicColor = (str) => {
  if (!str || typeof str !== "string") return "#E3007E";
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash);
  }
  const h = Math.abs(hash) % 360;
  const s = 65 + (Math.abs(hash >> 3) % 25); // 65-90% saturation
  const l = 45 + (Math.abs(hash >> 6) % 20); // 45-65% lightness

  // HSL to RGB conversion
  const c = (1 - Math.abs(2 * (l / 100) - 1)) * (s / 100);
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l / 100 - c / 2;
  let r = 0, g = 0, b = 0;

  if (h >= 0 && h < 60) { r = c; g = x; b = 0; }
  else if (h >= 60 && h < 120) { r = x; g = c; b = 0; }
  else if (h >= 120 && h < 180) { r = 0; g = c; b = x; }
  else if (h >= 180 && h < 240) { r = 0; g = x; b = c; }
  else if (h >= 240 && h < 300) { r = x; g = 0; b = c; }
  else { r = c; g = 0; b = x; }

  const toHex = (n) => Math.round((n + m) * 255).toString(16).padStart(2, "0");
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`.toUpperCase();
};

/**
 * Resolve ANY color input (name or hex code) to guaranteed valid hex code
 */
export const resolveHex = (code, name) => {
  if (isValidHex(code)) return normalizeHex(code);
  if (isValidHex(name)) return normalizeHex(name);

  const searchTerms = [name, code]
    .filter(Boolean)
    .map((s) => String(s).trim().toLowerCase());

  // 1. Exact catalog match
  for (const term of searchTerms) {
    const found = FABRIC_COLORS.find(
      (c) => c.name.toLowerCase() === term
    );
    if (found) return found.hex;
  }

  // 2. CSS color name resolution
  for (const term of searchTerms) {
    const cssHex = cssNameToHex(term);
    if (cssHex) return cssHex;
  }

  // 3. Partial catalog match
  for (const term of searchTerms) {
    const partial = FABRIC_COLORS.find(
      (c) =>
        term.includes(c.name.toLowerCase()) ||
        c.name.toLowerCase().includes(term)
    );
    if (partial) return partial.hex;
  }

  // 4. Deterministic fallback for named colors
  if (name && typeof name === "string" && name.trim()) {
    return getDeterministicColor(name.trim());
  }

  return "";
};

/**
 * Search colors across catalog, CSS colors, and custom queries.
 * Returns ranked list of colors with swatches and family tags.
 */
export const searchColors = (query = "", limit = 15) => {
  const q = (query || "").trim().toLowerCase();
  if (!q) {
    return FABRIC_COLORS.filter((c) => c.popular).slice(0, limit);
  }

  // Check if query is a direct hex code
  if (isValidHex(q) || (/^[A-Fa-f0-9]{3,6}$/.test(q) && (q.length === 3 || q.length === 6))) {
    const hex = normalizeHex(q);
    const closest = findClosestFabricColor(hex);
    return [
      {
        name: closest ? `${closest.name} (${hex})` : `Hex ${hex}`,
        hex: hex,
        family: closest ? closest.family : "Custom Hex",
        isHex: true,
      },
      ...FABRIC_COLORS.filter((c) => c.hex.toLowerCase().includes(q.toLowerCase())).slice(0, limit - 1),
    ];
  }

  const exact = [];
  const startsWith = [];
  const wordStarts = [];
  const contains = [];
  const seenNames = new Set();

  for (const item of FABRIC_COLORS) {
    const nameLower = item.name.toLowerCase();
    const familyLower = item.family.toLowerCase();
    const key = `${item.name.toLowerCase()}_${item.hex.toLowerCase()}`;

    if (seenNames.has(key)) continue;

    if (nameLower === q) {
      exact.push(item);
      seenNames.add(key);
    } else if (nameLower.startsWith(q)) {
      startsWith.push(item);
      seenNames.add(key);
    } else if (nameLower.split(/\s+/).some((w) => w.startsWith(q))) {
      wordStarts.push(item);
      seenNames.add(key);
    } else if (
      nameLower.includes(q) ||
      familyLower.includes(q) ||
      item.hex.toLowerCase().includes(q)
    ) {
      contains.push(item);
      seenNames.add(key);
    }
  }

  // Check CSS color resolution if no exact match found yet
  if (exact.length === 0) {
    const cssHex = cssNameToHex(q);
    if (cssHex && !seenNames.has(`${q}_${cssHex.toLowerCase()}`)) {
      const formattedName = q.charAt(0).toUpperCase() + q.slice(1);
      const closest = findClosestFabricColor(cssHex);
      exact.unshift({
        name: formattedName,
        hex: cssHex,
        family: closest ? closest.family : "Standard Color",
      });
      seenNames.add(`${q}_${cssHex.toLowerCase()}`);
    }
  }

  return [...exact, ...startsWith, ...wordStarts, ...contains].slice(0, limit);
};
